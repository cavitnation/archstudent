  <h2>Minimum floor areas</h2>
  <p>These are widely-cited planning minimums for comfortable rooms. The UK Nationally Described Space Standard sets a hard floor of <strong>7.5 sqm</strong> for a single bedroom and <strong>11.5 sqm</strong> for a double/twin — see our <a href="/standards/minimum-room-sizes/">minimum room sizes</a> page.</p>

  <table class="data">
    <tr><th>Room type</th><th>Typical minimum area</th><th>Indicative size</th></tr>
    <tr><td>Single bedroom</td><td>~7.5 sqm</td><td>~2.1 × 3.6 m; min 2.15 m wide (NDSS)</td></tr>
    <tr><td>Double bedroom</td><td>~11.5 sqm</td><td>~2.75 × 4.2 m; min 2.75 m wide (NDSS)</td></tr>
    <tr><td>Twin bedroom</td><td>~11.5 sqm</td><td>Two singles need space between beds</td></tr>
  </table>

  <p>For a twin, allow a gap of at least <strong>750 mm</strong> between the two beds so each is independently accessible.</p>

