  <h2>Clearances around beds</h2>
  <p>You need space to make the bed, get in and out, and pass along its side. Use these planning clearances:</p>
  <ul>
    <li><strong>Access side of a bed:</strong> at least 700–750 mm clear to walk and dress.</li>
    <li><strong>Both sides of a double</strong> should ideally have access; a minimum of ~600 mm one side is a tight limit.</li>
    <li><strong>Foot of the bed:</strong> allow 500–700 mm to pass or make the bed.</li>
    <li><strong>In front of a wardrobe:</strong> around 750 mm to open doors and remove clothing.</li>
  </ul>

  <div class="callout"><strong>Tip.</strong> Place at least one long side of a double bed against nothing but circulation space. A double pushed into a corner may fit on paper but is miserable to make and to sleep in.</div>

