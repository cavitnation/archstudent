  <h2>Fixture sizes</h2>
  <p>Standard sanitaryware falls within predictable ranges. Use these as planning figures and confirm the exact model early, because compact and comfort-height variants differ by tens of millimetres.</p>

  <table class="data">
    <tr><th>Fixture</th><th>Typical size (W × D)</th><th>Notes</th></tr>
    <tr><td>WC (toilet)</td><td>~370 × 600–700 mm</td><td>Pan projects 600–700 mm from wall; seat ~400–450 mm high</td></tr>
    <tr><td>Basin (wall/pedestal)</td><td>500–600 × 400–450 mm</td><td>Cloakroom basins from ~360 mm wide; rim ~800–850 mm high</td></tr>
    <tr><td>Bath (standard)</td><td>1700 × 700 mm</td><td>Compact 1500–1600 mm; also 750–800 mm wide variants</td></tr>
    <tr><td>Shower tray</td><td>760 × 760 mm (min)</td><td>900 × 900 mm comfortable; 1200 × 800 mm rectangular</td></tr>
  </table>

  <h2>Activity / clearance space</h2>
  <p>Each fixture needs an unobstructed zone in front of it. These activity spaces may overlap with a circulation route but should not overlap each other where two people might use adjacent fixtures.</p>

  <table class="data">
    <tr><th>Fixture</th><th>Activity space in front</th><th>Notes</th></tr>
    <tr><td>WC</td><td>~600 wide × 600–800 deep</td><td>Measured from the front of the pan</td></tr>
    <tr><td>Basin</td><td>~700 wide × 700 deep</td><td>Room to lean forward to wash</td></tr>
    <tr><td>Bath</td><td>~700 deep along the length</td><td>Space to stand and step in/out</td></tr>
    <tr><td>Shower</td><td>~700 × 700 at the opening</td><td>For drying and dressing</td></tr>
  </table>

  <div class="callout"><strong>Tip.</strong> When space is tight, let activity zones overlap the main circulation path but never let two fixtures' activity zones overlap each other — that is what makes a compact bathroom feel usable rather than awkward.</div>

  <h2>Minimum layouts</h2>
  <p>These commonly-cited minimums produce a functional room; comfort and accessibility push the figures higher.</p>
  <ul>
    <li><strong>Cloakroom (WC + basin):</strong> around 900 × 1500 mm — enough for a corner basin and a WC with turning room.</li>
    <li><strong>Shower room (WC + basin + shower):</strong> roughly 1700 × 2000 mm.</li>
    <li><strong>Full bathroom (WC + basin + bath):</strong> typically from about 1800 × 2000 mm; a bath along the short wall of a ~2100 mm room fits a 1700 mm tub with clearance.</li>
    <li><strong>Accessible bathrooms</strong> require significantly more space for wheelchair turning circles (a 1500 mm diameter turning space is a common target) and side transfer to the WC.</li>
  </ul>

  <h2>Heights and mounting</h2>
