  <p>Multi-storey homes require more: for instance a 3b5p house over two storeys is around <strong>93 m²</strong> rather than 86 m², and three-storey homes more again.</p>

  <div class="callout"><strong>Tip.</strong> The GIA figure is a floor, not a target. It assumes a built-in storage allowance is included; if you strip storage out to hit the number, the home will not comply.</div>

  <h2>Minimum bedroom areas</h2>
  <p>Within the overall GIA, the standard sets floors for individual bedrooms and minimum widths so the room is genuinely usable.</p>

  <table class="data">
    <tr><th>Bedroom</th><th>Minimum area</th><th>Minimum width</th></tr>
    <tr><td>Single</td><td>7.5 m²</td><td>2.15 m</td></tr>
    <tr><td>Double / twin</td><td>11.5 m²</td><td>2.55–2.75 m</td></tr>
  </table>

  <p>A double bedroom (or twin) at least <strong>2.75 m</strong> wide is the common target; a narrower "double" quickly fails to take a bed with access on both sides. See <a href="/standards/bedroom-sizes/">bedroom sizes</a> for bed and clearance detail.</p>

  <h2>Ceiling height and storage</h2>
  <ul>
    <li><strong>Floor-to-ceiling height:</strong> the NDSS expects a minimum of <strong>2.3 m</strong> over at least 75% of the gross internal area of each habitable room. See <a href="/standards/ceiling-heights/">ceiling heights</a>.</li>
    <li><strong>Built-in storage:</strong> a general storage allowance of about <strong>1.0 m²</strong> for one- and two-person dwellings, increasing with occupancy (roughly +0.5 m² per additional person, subject to the standard).</li>
    <li>Any area with a floor-to-ceiling height below 1.5 m is <strong>not counted</strong> toward the GIA — relevant in loft rooms and under sloped ceilings.</li>
  </ul>

  <h2>Why it matters</h2>
  <p>The NDSS exists because dwellings can meet building regulations for safety yet still be too small to live in comfortably. As a student, quoting the NDSS in a housing scheme shows your plan is grounded in real policy rather than guesswork. Wales, Scotland and Northern Ireland use their own standards, so confirm which applies.</p>

  <div class="callout warn"><strong>Always verify.</strong> These figures reflect the England Nationally Described Space Standard and general practice; adoption and exact minima vary by local plan and nation, so confirm against the current standard and the building regulations for your project and country.</div>

