  <h2>How the standard works</h2>
  <p>The NDSS defines a home by <strong>bedrooms (b)</strong> and <strong>bed spaces / persons (p)</strong> — for example a "2b4p" flat is a two-bedroom home designed for four people. The bigger the household it serves, the larger the minimum GIA. Areas increase with the number of storeys because circulation (stairs and landings) consumes floor area.</p>

  <h2>Minimum gross internal areas (single storey)</h2>
  <p>Indicative NDSS minimum GIAs for common dwelling types on one level:</p>

