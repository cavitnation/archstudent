  </table>

  <h2>Landing, balcony and floor-edge guarding</h2>
  <p>Where the edge is a level surface rather than a stair — a landing, balcony, gallery, roof terrace or the edge of a floor — the guarding is normally taller. In dwellings and general locations the guarding to such edges is typically at least 1100&nbsp;mm high, measured from the finished floor (or from the datum on a balcony) to the top of the rail. This taller height reflects that people may lean, stand or gather at these edges rather than move past quickly.</p>
