    <tr><td>Balcony / external edge</td><td>1100 mm typical</td><td>Confirm for occupancy type</td></tr>
  </table>

  <div class="callout"><strong>Keep the two apart.</strong> Handrail height (900–1000&nbsp;mm) is about being able to grip while moving on a stair. Guarding height (1100&nbsp;mm to a level edge) is about not toppling over an edge where you stand. A stair balustrade often does both jobs; a balcony edge only does the second.</div>

  <h2>The 100mm sphere gap rule</h2>
  <p>Guarding must not only be tall enough, it must stop a small child slipping or climbing through. The widely used rule is that guarding should be constructed so a 100&nbsp;mm sphere cannot pass through any gap in it — so vertical balusters are typically spaced at less than 100&nbsp;mm clear. Designers also avoid easily-climbable horizontal rails where young children are present, since a ladder-like guard defeats the purpose of the height.</p>
