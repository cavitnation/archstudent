  <h2>Stair handrail height</h2>
  <p>On a flight of stairs the handrail is typically set at 900–1000&nbsp;mm measured vertically from the pitch line (the line touching the nosings of the treads) to the top of the rail. The same height generally applies on the sloping part of the stair and on landings that are part of the flight. Handrails should be graspable and are usually provided on at least one side, with both sides on wider stairs.</p>
