  <h2>When is guarding required?</h2>
  <p>As a general trigger, guarding is provided wherever there is a drop that people could fall down. Internally this is commonly taken as a difference in level of more than about 600&nbsp;mm (roughly two steps); externally, guarding is usually required at any level people can reach where there is a fall, such as balconies and terraces. Below the internal threshold guarding may be omitted, but a handrail can still be sensible for support. Guarding must also be strong enough to resist people leaning and being pushed against it.</p>
  <table class="data">
    <tr><th>Situation</th><th>Guarding typically needed?</th><th>Notes</th></tr>
    <tr><td>Internal drop &gt; ~600 mm</td><td>Yes</td><td>Roughly two or more steps</td></tr>
    <tr><td>Internal drop &lt; ~600 mm</td><td>Often not required</td><td>Handrail may still help</td></tr>
    <tr><td>Balcony / terrace / roof edge</td><td>Yes</td><td>Any accessible external fall</td></tr>
  </table>

  <div class="callout warn"><strong>Always verify.</strong> These figures follow UK Approved Documents K and M as general guidance. Heights change with occupancy (e.g. buildings used by very young children) and countries use different codes (e.g. the IBC in the US uses a 42&nbsp;inch guard and a 4&nbsp;inch sphere). Confirm the rules for your project type and location.</div>

