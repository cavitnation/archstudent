    <tr><td>Clear turning space</td><td>1500 mm diameter</td></tr>
    <tr><td>Transfer space beside WC</td><td>typically ~950 mm clear</td></tr>
    <tr><td>WC centreline from side wall</td><td>typically ~470 mm</td></tr>
    <tr><td>WC seat height</td><td>~480 mm above floor</td></tr>
  </table>

  <h2>Transfer space</h2>
  <p>A wheelchair user parks alongside the pan and transfers sideways, so one side of the WC must stay completely clear — no basin, no bin. This transfer zone is typically 950&nbsp;mm wide next to the pan. Left- and right-hand versions are mirror images; in larger buildings you provide both handednesses so users have a choice. Never block the transfer side with fittings.</p>

  <div class="callout"><strong>Fix these first.</strong> Treat the 2200 × 1500&nbsp;mm room, the 1500&nbsp;mm turning circle and the clear transfer side as immovable constraints, then arrange the basin, rails and fittings around them. A poorly laid-out accessible WC is one of the commonest reasons drawings get rejected.</div>

  <h2>Grab rail positions</h2>
  <p>Grab rails give the leverage to transfer and stand. Rails are commonly set with horizontal rails at about 680&nbsp;mm above the floor, a drop-down rail on the transfer side, and a vertical rail near the WC. Heights are measured to the top of the rail. Rails should visually contrast with the wall so partially sighted users can find them.</p>
  <table class="data">
    <tr><th>Rail</th><th>Typical height / note</th></tr>
    <tr><td>Horizontal rails</td><td>~680 mm above floor</td></tr>
    <tr><td>Drop-down rail (transfer side)</td><td>~680 mm, folds up when not used</td></tr>
    <tr><td>Vertical rail beside WC</td><td>lower fixing ~600 mm, upper ~1100 mm</td></tr>
    <tr><td>Basin, WC and rails</td><td>visually contrast with walls</td></tr>
  </table>

  <h2>Ambulant accessible cubicle</h2>
  <p>Not every disabled user is a wheelchair user. An ambulant accessible cubicle serves people who walk but need support — those with crutches, limited mobility or reduced strength. It is larger than a standard cubicle, typically 1500 × 1200&nbsp;mm internally, fitted with grab rails on both sides and an outward-opening door. In larger WC blocks at least one ambulant cubicle is provided alongside standard ones.</p>
  <table class="data">
    <tr><th>Cubicle type</th><th>Typical size</th></tr>
