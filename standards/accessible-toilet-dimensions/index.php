    <tr><td>Door</td><td>outward opening, 450 mm min clear at latch</td></tr>
  </table>

  <h2>Why this matters</h2>
  <p>Accessible sanitary provision is often a planning and Building Regulations requirement. Treat the room size, the turning circle and the clear transfer side as fixed, get the handedness right for the building, and the rest of the layout follows.</p>

  <div class="callout warn"><strong>Always verify.</strong> Figures follow UK Approved Document M and BS 8300 as general guidance. Dimensions and rail layouts differ between building types and countries (e.g. the ADA in the US sets its own clear-floor and grab-bar geometry). Confirm the rules for your project and location.</div>

