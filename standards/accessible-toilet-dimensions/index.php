  <h2>The wheelchair-accessible WC</h2>
  <p>UK Approved Document M sets a unisex wheelchair-accessible toilet at a minimum internal size of about 2200 × 1500&nbsp;mm (depth × width). That footprint is not arbitrary: it holds the WC, wash basin, a clear 1500&nbsp;mm turning circle, and the critical transfer space to one side of the pan. The door opens outward so the floor space inside stays clear, and an emergency alarm pull cord reaches to the floor.</p>
  <table class="data">
    <tr><th>Element</th><th>Dimension</th></tr>
