  <p>Leave <strong>300–450&nbsp;mm</strong> between the front of a sofa and a coffee table — close enough to reach a mug, far enough for legs — and a walkway of at least 600&nbsp;mm (ideally 750&nbsp;mm) behind or beside a seating group. A rough guide for TV viewing distance is 2–2.5 × the screen width.</p>

