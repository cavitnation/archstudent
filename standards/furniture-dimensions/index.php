  <h2>Clearances — the numbers people forget</h2>
  <div class="callout"><strong>Rules of thumb.</strong> Main walkway ≥ <strong>900&nbsp;mm</strong>; secondary or occasional route ≥ <strong>600&nbsp;mm</strong>; space to pull a dining chair out and pass behind it <strong>900–1100&nbsp;mm</strong>; drawer or wardrobe door to open into <strong>750–900&nbsp;mm</strong>.</div>
  <ul>
    <li><strong>Around a dining table:</strong> allow ~1000&nbsp;mm from table edge to wall so chairs pull out and people pass.</li>
    <li><strong>In front of storage:</strong> leave the depth of the open drawer or door plus room to stand — 750&nbsp;mm+.</li>
    <li><strong>Beside a bed:</strong> 700&nbsp;mm minimum access; 900&nbsp;mm where a wardrobe faces it.</li>
    <li><strong>Wheelchair turning:</strong> a 1500&nbsp;mm clear circle is the usual accessible benchmark.</li>
    <li><strong>Overlapping zones:</strong> where two activity zones overlap, plan for the larger of the two, not the sum.</li>
  </ul>

  <div class="callout warn"><strong>Always verify.</strong> These are typical figures and vary by manufacturer, market and era — UK, US and European bed and mattress sizes in particular are all different. Measure the actual products specified, and check accessibility standards (e.g. UK Approved Document M, or ADA in the US) for clearances on any project that must be inclusive.</div>

