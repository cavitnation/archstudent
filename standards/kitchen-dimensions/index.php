  <h2>Worktops</h2>
  <p>The standard worktop working height is typically <strong>900 mm</strong> above finished floor level, though many designers now set this to suit the primary user (roughly 850–950 mm). Depth is usually <strong>600 mm</strong> to match base units with a small overhang. The gap between the worktop and the underside of wall units — the splashback zone — is typically <strong>450–600 mm</strong>.</p>

  <table class="data">
    <tr><th>Element</th><th>Dimension</th><th>Notes</th></tr>
    <tr><td>Worktop height</td><td>900 mm (typ.)</td><td>850–950 mm to suit user; adjust for tall/short cooks</td></tr>
    <tr><td>Worktop depth</td><td>600 mm</td><td>28–40 mm typical thickness; overhangs base by ~20 mm</td></tr>
    <tr><td>Splashback gap</td><td>450–600 mm</td><td>Worktop to underside of wall units</td></tr>
    <tr><td>Upstand</td><td>~100 mm</td><td>Where a full splashback is not used</td></tr>
  </table>

  <h2>Base and wall units</h2>
  <p>Carcass widths are modular, rising in <strong>100 mm</strong> increments — commonly 300, 400, 500, 600, 800 and 1000 mm. Base units are typically <strong>720 mm</strong> tall (carcass), sitting on a plinth of about <strong>150 mm</strong> to reach the 870–900 mm worktop line. Wall units are usually <strong>720 mm</strong> tall and <strong>300 mm</strong> deep.</p>

  <table class="data">
    <tr><th>Unit</th><th>Dimension</th><th>Notes</th></tr>
    <tr><td>Base unit height (carcass)</td><td>720 mm</td><td>Plus ~150 mm plinth + worktop</td></tr>
    <tr><td>Base unit depth</td><td>560–600 mm</td><td>560 mm carcass under a 600 mm top</td></tr>
    <tr><td>Wall unit height</td><td>720 / 900 mm</td><td>Shorter units common over hobs/sinks</td></tr>
    <tr><td>Wall unit depth</td><td>300 mm</td><td>Kept shallow to clear the head/worktop</td></tr>
    <tr><td>Unit widths</td><td>300–1000 mm</td><td>In 100 mm modular steps</td></tr>
    <tr><td>Tall/larder unit height</td><td>1970–2150 mm</td><td>Full-height storage or built-in ovens</td></tr>
  </table>

  <h2>Appliance gaps</h2>
  <p>Integrated and freestanding appliances are designed to slot into standard openings. Allow small tolerances so units are not forced.</p>
  <ul>
    <li><strong>Under-counter (dishwasher, washing machine, fridge):</strong> 600 mm wide opening (appliance ~595 mm).</li>
    <li><strong>Freestanding cooker:</strong> 600 mm typical, 900 mm for a range.</li>
    <li><strong>Built-in single oven:</strong> housing for a 600 mm wide unit.</li>
    <li><strong>American-style fridge/freezer:</strong> 900–1000 mm — check the manufacturer sheet.</li>
  </ul>

  <div class="callout"><strong>Tip.</strong> Always leave a few millimetres of tolerance around freestanding appliances — a nominal 600 mm gap suits a 595–597 mm appliance and allows for out-of-plumb walls.</div>

  <h2>The work triangle</h2>
  <p>The classic ergonomic rule links the three main work centres — <strong>sink, hob and refrigerator</strong>. Each leg of the triangle should be roughly <strong>1.2–2.7 m</strong>, with the total perimeter typically between <strong>4 m and 8 m</strong>. Keep through-traffic out of the triangle so cooking is not interrupted.</p>

  <table class="data">
    <tr><th>Element</th><th>Dimension</th><th>Notes</th></tr>
    <tr><td>Single triangle leg</td><td>1.2–2.7 m</td><td>Sink–hob, hob–fridge, fridge–sink</td></tr>
    <tr><td>Total triangle perimeter</td><td>4–8 m</td><td>Under 4 m feels cramped; over 8 m tiring</td></tr>
  </table>

  <h2>Clearances between runs</h2>
  <p>Where two runs of units face each other (galley or island kitchens), leave a comfortable gangway so drawers and appliance doors can open with someone standing at the opposite run.</p>
  <ul>
    <li><strong>Minimum walkway:</strong> ~1000 mm between facing units.</li>
    <li><strong>Comfortable / two-person working:</strong> 1200–1500 mm.</li>
    <li><strong>Appliance door + person:</strong> allow at least 1050–1100 mm so an open oven or dishwasher door still lets someone pass.</li>
  </ul>

  <div class="callout warn"><strong>Always verify.</strong> These figures reflect UK guidance and general practice; confirm worktop heights, appliance cut-outs and clearances against the manufacturer's data and the building regulations and standards for your project and country.</div>

