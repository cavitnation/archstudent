  <h1>Kitchen dimensions</h1>
  <p class="muted">The everyday numbers behind fitted kitchens — worktops, units, appliance gaps, clearances and the work triangle.</p>

  <p class="lead">Fitted kitchens across the UK and Europe are built around a small set of near-universal dimensions. Cabinets, appliances and worktops are all coordinated so that components from different manufacturers interchange. Learn these figures once and you can lay out a workable kitchen from memory.</p>

