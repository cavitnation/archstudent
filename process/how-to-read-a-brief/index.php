  <h2>Read it three times, differently</h2>
  <p>The first read is for the story: who is this for, where is it, what is it meant to do in the world? Don't take notes yet &mdash; just get the shape of it. The second read is forensic: highlight every number, area, adjacency and rule. The third read is sceptical: for each requirement, ask &ldquo;why is this here, and what does it really want?&rdquo; Most students only ever do the second read, and it shows &mdash; their projects satisfy the brief without ever understanding it.</p>

  <h2>Requirements versus intentions</h2>
  <p>This is the single most useful distinction you can make. Split everything the brief says into two columns.</p>
  <ul>
    <li><strong>Requirements</strong> are the hard facts you must deliver: a 60&nbsp;m&sup2; workshop, step-free access, a budget, a site boundary. Break one and the project fails.</li>
    <li><strong>Intentions</strong> are the softer language about ambition: &ldquo;a welcoming space&rdquo;, &ldquo;a building that brings the community together&rdquo;, &ldquo;flexible for the future&rdquo;. These are what the client actually cares about &mdash; and they are where your design earns its keep.</li>
  </ul>
  <p>Requirements tell you what you cannot do. Intentions tell you what would make the project <em>good</em>. A design that hits every requirement but ignores the intentions is competent and forgettable. Keep both columns visible on your desk throughout the project &mdash; tutors will push on the intentions long after the requirements are settled.</p>

  <div class="callout"><strong>Studio tip.</strong> Circle the adjectives. &ldquo;Calm&rdquo;, &ldquo;robust&rdquo;, &ldquo;playful&rdquo;, &ldquo;generous&rdquo; &mdash; these words are the client's real success criteria hiding in plain sight. Design toward the adjectives, not just the areas.</div>

  <h2>Decoding the area schedule</h2>
  <p>The schedule of accommodation looks like a boring table. It is actually the plan in disguise. Read it as relationships, not just totals.</p>
  <ul>
    <li><strong>Add it up honestly.</strong> Sum the net areas, then add circulation, structure and walls &mdash; typically 20&ndash;35% on top for the gross. If your site can't hold the gross figure, you have a fundamental problem to raise now, not in week eight.</li>
    <li><strong>Look for adjacencies.</strong> What needs to be next to what? What must be kept apart (noisy from quiet, public from private, clean from dirty)? These pairings are the seed of your plan diagram.</li>
    <li><strong>Find the hierarchy.</strong> Which space is the heart of the building? The schedule rarely says so directly, but the sizes and the intentions together will tell you.</li>
    <li><strong>Question the numbers.</strong> An oddly precise area usually has a reason &mdash; a piece of equipment, a code, a standard. An oddly round one may be a guess you can challenge.</li>
  </ul>

  <h2>Mapping the constraints</h2>
  <p>Constraints are gifts &mdash; they narrow the field and give the design something to push against. Sort them by how much they truly bind you. Fixed constraints (the site, budget, planning rules, accessibility, orientation) are the frame. Soft constraints (preferences, wish-lists, &ldquo;ideally&rdquo; statements) are negotiable and worth testing. Knowing which is which stops you agonising over things you could change and blindsiding yourself with things you can't.</p>

  <h2>Write the brief back</h2>
  <p>The most professional habit you can build as a student: after reading, write the brief back in your own words and hand it to whoever set it. A short paragraph &mdash; &ldquo;As I understand it, you need&hellip; so that&hellip; and above all it should feel&hellip;&rdquo; &mdash; does three things. It proves you understood. It surfaces the gaps and contradictions early. And it quietly lets you reframe the project toward the idea you find most interesting, with the client's agreement. This is what real architects do at the first meeting, and it consistently separates the strong students from the rest.</p>

  <h2>Ask the right questions</h2>
  <p>Vague questions get vague answers. Ask questions that force a decision or reveal a value.</p>
  <ul>
    <li>&ldquo;If you had to lose one space to save money, which goes first?&rdquo; &mdash; exposes the true hierarchy.</li>
    <li>&ldquo;What does success look like a year after it opens?&rdquo; &mdash; converts intentions into measurable ambition.</li>
    <li>&ldquo;Is this number fixed, or a starting point?&rdquo; &mdash; separates hard from soft constraints.</li>
    <li>&ldquo;What building do you love, and what do you hate?&rdquo; &mdash; gives you the client's unspoken taste.</li>
    <li>&ldquo;Who else has to say yes to this?&rdquo; &mdash; reveals the real stakeholders behind the brief.</li>
  </ul>

  <div class="callout warn"><strong>Common trap.</strong> Treating the brief as fixed and complete. Briefs are always partial, sometimes contradictory, and occasionally wrong. Your job is not to obey it but to interpret it &mdash; and a well-argued reinterpretation, backed by the client's own words, is often the most original move in the whole project.</div>

