  <h2>Why precedents matter</h2>
  <p>Every problem you face as a student, someone has faced before &mdash; how to bring light deep into a plan, how to sit a heavy building on a slope, how to make a corridor feel like a place. Precedent studies are how architects learn from that accumulated intelligence without starting from zero. Done well, they give you a library of tested strategies you can adapt. Done badly, they become copying with extra steps. The difference is entirely in what you choose to look at.</p>

  <h2>Choosing the right precedents</h2>
  <p>Don't pick by fame or by prettiness. Pick by <strong>problem</strong>. A precedent is only useful if it answers a question you actually have. Before you search, write down your two or three hardest problems &mdash; then hunt for buildings that solved <em>those</em>, even if they look nothing like what you're designing.</p>
  <ul>
    <li><strong>By problem, not by type.</strong> If your struggle is a deep, dark plan, a warehouse conversion may teach you more than another building of your programme.</li>
    <li><strong>Choose a range.</strong> One canonical masterwork for the principle, one obscure or ordinary building for the reality of how it's really done.</li>
    <li><strong>Prefer ones you can visit or find drawings of.</strong> A building you only know from one hero photo is almost useless &mdash; you need plans and sections.</li>
    <li><strong>Three studied deeply beat ten skimmed.</strong> Depth is where the learning lives.</li>
  </ul>

  <div class="callout"><strong>Studio tip.</strong> Name the question at the top of every precedent sheet: &ldquo;How does this building get daylight to its centre?&rdquo; Then let that question decide what you draw and ignore everything else. A focused study is worth ten comprehensive ones.</div>

  <h2>What to actually analyse</h2>
  <p>Move past &ldquo;it's made of concrete and it's very nice.&rdquo; Interrogate the decisions.</p>
  <ul>
    <li><strong>Organisation.</strong> How is the plan structured &mdash; a spine, a grid, rooms around a court, served and servant zones? What's the parti?</li>
    <li><strong>Section.</strong> Often where the real idea lives. How do levels, light and volume work vertically?</li>
    <li><strong>Circulation.</strong> How do you move through it, and how does the route shape the experience?</li>
    <li><strong>Structure &amp; light.</strong> How the building stands up and how daylight enters &mdash; usually deeply linked.</li>
    <li><strong>Response to site.</strong> How it meets the ground, the street, the orientation.</li>
    <li><strong>Threshold &amp; scale.</strong> How you arrive, and how it feels big or intimate at the moments that matter.</li>
  </ul>

  <h2>Redraw to learn</h2>
  <p>You do not understand a building until you have redrawn it. Reading a plan is passive; tracing and rebuilding it forces you to notice every decision the architect made &mdash; the wall thicknesses, the exact position of a stair, the way a grid slips. Redraw everything to a consistent scale so your precedents can be compared side by side. Strip out the graphic style and the furniture; keep the structure of the idea. Draw the diagram <em>under</em> the drawing &mdash; the parti, the circulation, the light. This is slow, and it is the single most valuable thing you can do. The knowledge ends up in your hand, not just your eyes.</p>

  <h2>Avoiding plagiarism</h2>
  <p>The line is simple: <strong>borrow strategies, never forms.</strong> Copying the shape of a precedent is plagiarism and, worse, pointless &mdash; the form solved <em>their</em> site and brief, not yours. Extracting the principle behind it and re-applying it to your own conditions is exactly what architects are supposed to do. &ldquo;They used a top-lit central spine to organise a deep plan&rdquo; is a principle you can honestly reuse. Lifting their elevation is not. Always credit your precedents openly in your work &mdash; naming your influences signals maturity, not weakness, and it forces you to be clear about what you actually took.</p>

  <div class="callout warn"><strong>Common trap.</strong> The precedent that never touches the design. If your studies sit in an appendix and your building would be identical without them, they were decoration. Precedent analysis has to change a decision to have been worth doing.</div>

  <h2>Turning analysis into your own moves</h2>
  <p>The final step is translation. For each principle you extracted, ask &ldquo;how does this apply to <em>my</em> site, <em>my</em> brief, <em>my</em> concept?&rdquo; and draw the adapted version immediately. Often you'll combine strategies from several precedents &mdash; the sectional idea from one, the circulation logic from another &mdash; and that recombination, tuned to your own conditions, is where originality genuinely comes from. Keep a running &ldquo;moves&rdquo; sheet: precedent on the left, principle in the middle, your adapted version on the right. That sheet is proof of thinking, and it's often the most convincing page in a review.</p>

