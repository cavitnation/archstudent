  <h1>Architecture thesis &amp; dissertation topic ideas</h1>
  <p class="lead muted">A method for choosing a topic you can live with for a year, plus more than twenty-five starting points grouped by theme.</p>

  <p>Your thesis is the longest, most self-directed piece of work in your degree, so the topic matters enormously &mdash; but students routinely lose weeks agonising over it. The ideas below are deliberately broad prompts, not finished questions; the real skill is narrowing one down until it is specific, arguable and achievable in your timeframe. Read the guidance first, then browse the lists for a spark.</p>

  <h2>How to choose a topic</h2>
  <p>A good thesis topic sits where three things overlap: something you genuinely care about, something with enough existing material to research, and something narrow enough to answer well. Work through these tests before you commit:</p>
  <ul>
    <li><strong>Follow a real curiosity.</strong> You will read about this for months. Pick a question that nags at you, not one that merely sounds impressive.</li>
    <li><strong>Narrow it ruthlessly.</strong> &ldquo;Sustainable housing&rdquo; is a field, not a thesis. &ldquo;How can low-cost passive cooling reduce overheating in UK terraced housing retrofits?&rdquo; is a thesis.</li>
    <li><strong>Check the evidence exists.</strong> Before you fall in love with a topic, confirm there are precedents, data, sites or literature you can actually reach.</li>
    <li><strong>Define a clear question or position.</strong> Examiners reward an argument, not a survey. Aim to prove, test or propose something.</li>
    <li><strong>Talk to your tutor early.</strong> A ten-minute conversation can save a month; supervisors know which topics are over-worn and which are quietly rich.</li>
  </ul>
  <p>Whether your thesis is a written dissertation or a design project, the same discipline applies: a sharp question makes every later decision easier.</p>

  <h2>Sustainability &amp; environment</h2>
  <ul>
    <li>Passive cooling and overheating risk in a warming climate.</li>
    <li>Embodied carbon: designing with timber, hemp or reclaimed materials.</li>
    <li>Retrofitting existing housing stock to net-zero standards.</li>
    <li>Water-sensitive urban design and flood-resilient neighbourhoods.</li>
    <li>Biophilic design and its measurable effect on wellbeing.</li>
  </ul>

  <h2>Housing</h2>
  <ul>
    <li>Co-housing and shared-living models for an ageing population.</li>
    <li>The future of the tower block: humanising high-density living.</li>
    <li>Affordable self-build and modular construction.</li>
    <li>Designing for multi-generational households.</li>
    <li>Housing for the homeless: dignity, permanence and support.</li>
  </ul>

  <h2>Urbanism &amp; public space</h2>
  <ul>
    <li>The 15-minute city and walkable neighbourhoods.</li>
    <li>Reclaiming streets from cars for people and play.</li>
    <li>The role of markets and informal trade in city life.</li>
    <li>Night-time economy and how cities are designed after dark.</li>
    <li>Public space, protest and the right to the city.</li>
  </ul>

  <h2>Adaptive reuse &amp; heritage</h2>
  <ul>
    <li>New life for redundant industrial and post-industrial sites.</li>
    <li>Converting redundant churches, chapels or civic buildings.</li>
    <li>Reusing the vast stock of empty high-street retail.</li>
    <li>Conservation versus intervention: how far should new work go?</li>
    <li>Car parks and infrastructure as future community assets.</li>
  </ul>

  <h2>Technology &amp; fabrication</h2>
  <ul>
    <li>Parametric and computational design in practice.</li>
    <li>3D printing and robotic fabrication in construction.</li>
    <li>Digital twins and building performance monitoring.</li>
    <li>Virtual and augmented reality in the design process.</li>
    <li>What AI-assisted design means for the profession.</li>
  </ul>

  <h2>Social &amp; cultural</h2>
  <ul>
    <li>Architecture for mental health and therapeutic environments.</li>
    <li>Inclusive and neurodiverse-friendly design.</li>
    <li>Designing schools around how children actually learn.</li>
    <li>Refugee and emergency shelter that lasts.</li>
    <li>Whose heritage? Decolonising the architecture curriculum and canon.</li>
  </ul>

