  <h2>Why the language matters</h2>
  <p>Architecture has a precise and sometimes intimidating vocabulary, and tutors will use it freely from your first week. Learning these words is not about sounding clever; it is about being able to describe your own ideas accurately and understand the feedback you are given. The table below collects the terms you will meet most often in studio, in crits and in the books on your reading list.</p>

  <table class="data">
    <thead>
      <tr><th>Term</th><th>Meaning</th></tr>
    </thead>
    <tbody>
      <tr><td>Parti</td><td>The central organising idea or concept of a design, often captured in a single simple diagram.</td></tr>
      <tr><td>Poch&eacute;</td><td>The solid, poured or filled-in parts of a plan (typically walls), shown blackened to read the space between them.</td></tr>
      <tr><td>Datum</td><td>A reference line, level or element against which other parts of a design are measured or aligned.</td></tr>
      <tr><td>Threshold</td><td>The point of transition between one space or condition and another, such as a doorway or the edge of inside and outside.</td></tr>
      <tr><td>Fenestration</td><td>The arrangement, proportion and design of windows and openings in a building&rsquo;s facade.</td></tr>
      <tr><td>Massing</td><td>The overall three-dimensional bulk, shape and composition of a building before detail is added.</td></tr>
      <tr><td>Tectonic</td><td>Relating to construction and structure as an expressive art — how a building is made becoming part of its meaning.</td></tr>
      <tr><td>Vernacular</td><td>Architecture built from local traditions, materials and climate rather than by formal design or fashion.</td></tr>
      <tr><td>Brise-soleil</td><td>A sun-breaker — fixed shading fins or louvres that block direct sunlight while allowing light and air.</td></tr>
      <tr><td>Cantilever</td><td>A structural element that projects horizontally beyond its support, held only at one end.</td></tr>
      <tr><td>Circulation</td><td>The routes through which people move around a building — corridors, stairs, lobbies and paths.</td></tr>
      <tr><td>Programme</td><td>The list of functions, rooms and activities a building must accommodate; the brief&rsquo;s spatial requirements.</td></tr>
      <tr><td>Brief</td><td>The statement of what a project must achieve — its purpose, users, constraints and requirements.</td></tr>
      <tr><td>Site</td><td>The physical location and its conditions — boundaries, orientation, topography, context and access.</td></tr>
      <tr><td>Context</td><td>The surroundings of a site — neighbouring buildings, streets, landscape and history that a design responds to.</td></tr>
      <tr><td>Facade</td><td>The external face of a building, especially the principal, street-facing elevation.</td></tr>
      <tr><td>Elevation</td><td>A flat, true-scale drawing of one face of a building, drawn without perspective.</td></tr>
      <tr><td>Section</td><td>A drawing showing a vertical cut through a building to reveal internal heights and relationships.</td></tr>
      <tr><td>Plan</td><td>A horizontal cut through a building viewed from above, showing the layout of spaces.</td></tr>
      <tr><td>Axonometric</td><td>A three-dimensional drawing that keeps lines parallel so measurements stay true along each axis.</td></tr>
      <tr><td>Scale</td><td>The ratio between a drawing and the real object, such as 1:100, and also the perceived size of a building relative to people.</td></tr>
      <tr><td>Proportion</td><td>The relationship of sizes between parts of a design and between the parts and the whole.</td></tr>
      <tr><td>Rhythm</td><td>The repetition of elements such as columns or windows that creates a visual pattern across a facade.</td></tr>
      <tr><td>Axis</td><td>An imaginary line about which elements are arranged symmetrically or along which movement is directed.</td></tr>
      <tr><td>Symmetry</td><td>A balanced arrangement of parts on either side of a central line or point.</td></tr>
      <tr><td>Hierarchy</td><td>The ordering of spaces or elements by importance, expressed through size, position or detail.</td></tr>
      <tr><td>Enfilade</td><td>A sequence of rooms aligned so their doorways form a continuous vista through the building.</td></tr>
      <tr><td>Loggia</td><td>A covered gallery or corridor open on one or more sides, often with columns.</td></tr>
      <tr><td>Portico</td><td>A roofed porch supported by columns, forming a formal entrance.</td></tr>
      <tr><td>Colonnade</td><td>A row of regularly spaced columns supporting an entablature or roof.</td></tr>
      <tr><td>Piloti</td><td>Columns or pillars that raise a building above ground level, leaving open space beneath.</td></tr>
      <tr><td>Curtain wall</td><td>A non-structural outer wall, usually of glass and metal, hung from the building&rsquo;s frame.</td></tr>
      <tr><td>Load-bearing</td><td>A wall or element that carries the weight of the structure above it down to the foundations.</td></tr>
      <tr><td>Span</td><td>The distance a structural member bridges between two supports.</td></tr>
      <tr><td>Truss</td><td>A rigid framework of triangulated members used to span long distances, often in roofs.</td></tr>
      <tr><td>Soffit</td><td>The underside of an architectural element such as an arch, beam, eave or ceiling.</td></tr>
      <tr><td>Cornice</td><td>A moulded projecting element that crowns the top of a wall or building.</td></tr>
      <tr><td>Plinth</td><td>The base or platform on which a building or column sits, raising it from the ground.</td></tr>
      <tr><td>Void</td><td>An intentional empty volume within a building, such as an atrium or double-height space.</td></tr>
      <tr><td>Atrium</td><td>A tall, often top-lit central space around which a building is organised.</td></tr>
      <tr><td>Genius loci</td><td>The distinctive character or &ldquo;spirit&rdquo; of a place that a design responds to.</td></tr>
      <tr><td>Adaptive reuse</td><td>Converting an existing building for a new purpose rather than demolishing it.</td></tr>
      <tr><td>Sustainability</td><td>Designing to reduce environmental impact across a building&rsquo;s whole life, from materials to energy use.</td></tr>
      <tr><td>Passive design</td><td>Using orientation, form and materials to control comfort with minimal mechanical energy.</td></tr>
      <tr><td>Thermal mass</td><td>The ability of heavy materials to absorb, store and release heat, smoothing temperature swings.</td></tr>
      <tr><td>Fabric</td><td>The physical material of a building — its walls, structure and surfaces, especially in an existing building.</td></tr>
    </tbody>
  </table>

  <div class="callout"><strong>Tip.</strong> Do not just memorise these words — use one deliberately in your next crit to describe your own design. Vocabulary sticks when you apply it to work you care about.</div>

