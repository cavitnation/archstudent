  <h2>The year out (and why it matters)</h2>
  <p>Between Part 1 and Part 2, most students take a "year out" working in practice. This is not just a box to tick - it is where the abstractions of studio finally meet real drawings, real clients and real deadlines. Practices expect year-out students to be genuinely useful: helping produce drawings, building models, researching products and sitting in on meetings. Many people find their confidence here, and a good year out can shape which kind of architecture you want to pursue. You will also log this time as part of your Professional Experience and Development Record (PEDR), the online logbook the profession uses to track your hours.</p>

  <h2>The timeline</h2>
  <p>Add it up and the classic route runs to roughly seven years: three years for Part 1, a year out, two years for Part 2, and further experience before Part 3. In reality it is rarely a clean seven. People take extra time out, work part time, switch practices, or pause and return. There is no prize for speed, and admissions tutors and employers see plenty of non-linear routes. What matters is that each stage is genuinely completed and recorded.</p>

  <h2>Alternative routes</h2>
  <p>The traditional full-time path is not the only way in. Apprenticeship routes now let you earn while you study, with an employer sponsoring your education across Parts 1, 2 and 3. Some universities offer part-time or distance study. These options can suit people who need an income throughout, or who are changing careers. They typically take longer end to end, but they reduce debt and keep you in continuous practice - which some students find far more motivating than another stint in the studio.</p>

  <div class="callout"><strong>Tip.</strong> Start your PEDR logbook early and keep it honest and up to date. Scrambling to reconstruct months of experience the week before an application is miserable, and supervisors respect a candidate who tracks their own development.</div>

  <h2>Doing it abroad</h2>
  <p>If you plan to practise outside the UK, the map changes completely. In the United States you will typically need a degree accredited by the NAAB, a period of documented experience, and the multi-part ARE examination administered through NCARB, with licensing handled state by state. Other countries have their own registration bodies, their own accredited degrees and their own titles. Qualifications do not always transfer automatically, though some mutual-recognition agreements exist. Decide early roughly where you want to end up, because it can influence which degree you choose now.</p>

  <h2>Is it worth it?</h2>
  <p>Seven years is a real commitment, and it is fair to weigh it seriously. But architecture is one of the few professions where you get to shape the physical world people live in, and the training - however long - gives you a rare mix of creative, technical and legal skill. If the work excites you, the length of the route is far less daunting from the other side.</p>

  <div class="callout warn"><strong>Routes vary.</strong> Qualification paths, titles and figures differ by country and change over time - always check the current requirements of your national registration body (e.g. ARB/RIBA in the UK, NCARB in the US).</div>

