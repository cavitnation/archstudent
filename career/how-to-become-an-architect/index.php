  <h2>The short version</h2>
  <p>In the UK, calling yourself an "architect" is protected by law. To use the title you must be registered with the Architects Registration Board (ARB). Registration is earned by completing three stages of education and experience - commonly known as RIBA Parts 1, 2 and 3 - which together take most people around seven years. It is a marathon of study, paid practice and a final professional exam, and almost everyone who qualifies has doubted the timeline at some point. That is normal.</p>

  <h2>The three parts</h2>
  <p>The UK route is built around three milestones. Part 1 is your undergraduate degree in architecture, typically three years. Part 2 is a further postgraduate qualification, usually a two-year Master of Architecture (MArch) or diploma. Part 3 is the final professional examination, taken after further practical experience, covering law, contracts, management and professional conduct. Sandwiched around these are periods of recorded work in practice.</p>

